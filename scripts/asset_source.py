"""Generated assembly sources of card data for the linker.

A Source holds sections of bytes and labels. The asset builder never knows an
address: src/secondsight/secondsight.ld and scripts/secondsight_fit.py place
each section by its name (.desc, .common, .vram).
"""


class Source:
    """One generated assembly source. Bytes go into the current section.
    Labels are global symbols for card code."""

    def __init__(self, title):
        self.lines = [f"; Generated by the asset builder: {title}."]

    def section(self, name):
        self.lines.append(f'        .section {name},"a",@progbits')
        return self

    def label(self, name):
        self.lines += [f"        .global {name}", f"{name}:"]
        return self

    def data(self, data):
        data = bytes(data)
        for i in range(0, len(data), 16):
            self.lines.append("        .byte " + ", ".join(f"0x{v:02X}" for v in data[i : i + 16]))
        return self

    def align(self, boundary):
        """Start the next byte at a multiple of BOUNDARY in the section."""
        self.lines.append(f"        .balign {boundary}")
        return self

    def text(self):
        return "\n".join(self.lines) + "\n"
