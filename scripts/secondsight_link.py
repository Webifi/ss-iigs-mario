"""The generated sources of the Second Sight program.

The asset builder writes its sources into build/secondsight/gen with
asset(); write_inputs() writes the list of them (sources.mk) that "make
secondsight" reads. scripts/secondsight_fit.py places their sections.
"""

from roms import ROOT

OUT = ROOT / "build/secondsight"
GENERATED = OUT / "gen"
_generated = []  # names of the generated sources of this build


def _write(path, text):
    """Write TEXT to PATH only when it differs: a file that does not change
    keeps its time, so make does not assemble or link again."""
    GENERATED.mkdir(parents=True, exist_ok=True)
    if not (path.exists() and path.read_text() == text):
        path.write_text(text)


def asset(name, source):
    """Write an asset_source.Source as build/secondsight/gen/NAME.s, the
    source "gen/NAME" of this build."""
    _write(GENERATED / f"{name}.s", source.text())
    if name not in _generated:
        _generated.append(name)
    return f"gen/{name}"


def write_inputs():
    """Write sources.mk: the generated sources that "make secondsight"
    assembles."""
    names = " ".join(_generated)
    _write(GENERATED / "sources.mk", f"# Generated by scripts/secondsight_link.py.\nGENERATED := {names}\n")
